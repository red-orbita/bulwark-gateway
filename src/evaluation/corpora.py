"""External evaluation corpora — independent, labeled ground truth.

``AttackGenerator`` produces attacks and labels every one of them ``BLOCK`` — a
circular benchmark, because the code that grades the exam also wrote it. Any
"detection rate" measured that way is unfalsifiable.

This module loads STATIC, EXTERNALLY-SOURCED labeled samples (malicious AND
benign) with provenance, so precision/recall are measured against ground truth
the gateway did not author. Bundled subsets live in ``src/evaluation/data/*.jsonl``
and are regenerated by ``scripts/fetch-eval-corpora.py`` from upstream,
permissively-licensed datasets (AdvBench, HarmBench, in-the-wild jailbreaks). See
``src/evaluation/data/manifest.json`` for per-source license and attribution.

Operators can point ``BULWARK_EVAL_DATASET_DIR`` at a directory of additional
JSONL shards (e.g. a full AdvBench / HarmBench / JailbreakBench / garak / PINT
download) to evaluate at scale without any code change — the loader merges those
shards with the bundled floor.

JSONL schema — one JSON object per line::

    {
      "text": "<prompt text>",           # required, non-empty string
      "label": "malicious" | "benign",   # required
      "category": "jailbreak" | ...,     # optional ThreatCategory value
      "source": "advbench",              # required provenance tag
      "source_id": "..."                 # optional upstream identifier
    }

Malformed lines are skipped (and counted) rather than aborting a whole shard, so
one bad row in an operator-supplied file cannot silently zero the benchmark.
"""

from __future__ import annotations

import json
import logging
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, Literal

from src.models import ThreatCategory, Verdict

from .attacks import Attack

logger = logging.getLogger(__name__)

# Bundled corpus directory (regenerated by scripts/fetch-eval-corpora.py).
DEFAULT_DATA_DIR = Path(__file__).parent / "data"

# Env var operators set to supply full/extra corpora without touching code.
_EXTERNAL_DIR_ENV = "BULWARK_EVAL_DATASET_DIR"

Label = Literal["malicious", "benign"]

_VALID_LABELS = ("malicious", "benign")

# Upstream corpora describe "harmful intent" behaviours that do not map cleanly
# onto a single Bulwark ThreatCategory. We record the true provenance in
# ``source`` and fold the category into the closest enforcement axis so the
# per-category rollup stays meaningful. Unmapped/None malicious samples default
# to JAILBREAK (the broadest adversarial-intent bucket).
_CATEGORY_ALIASES: dict[str, ThreatCategory] = {
    "harmful": ThreatCategory.JAILBREAK,
    "harmful_content": ThreatCategory.JAILBREAK,
    "harmful_behavior": ThreatCategory.JAILBREAK,
    "jailbreak": ThreatCategory.JAILBREAK,
    "prompt_injection": ThreatCategory.PROMPT_INJECTION,
    "injection": ThreatCategory.PROMPT_INJECTION,
    "exfiltration": ThreatCategory.EXFILTRATION,
    "credential_access": ThreatCategory.CREDENTIAL_ACCESS,
}

_DEFAULT_MALICIOUS_CATEGORY = ThreatCategory.JAILBREAK


def _coerce_category(raw: str | None) -> ThreatCategory:
    """Map a free-form category string onto a ThreatCategory (never raises)."""
    if not raw:
        return _DEFAULT_MALICIOUS_CATEGORY
    key = raw.strip().lower()
    if key in _CATEGORY_ALIASES:
        return _CATEGORY_ALIASES[key]
    try:
        return ThreatCategory(key)
    except ValueError:
        return _DEFAULT_MALICIOUS_CATEGORY


@dataclass(frozen=True)
class LabeledSample:
    """A single externally-sourced, labeled evaluation sample.

    ``label`` is the independent ground truth (not derived from any Bulwark
    verdict). ``source``/``source_id`` preserve provenance so a report can show
    per-dataset recall and a reviewer can audit exactly what was tested.
    """

    text: str
    label: Label
    source: str
    category: ThreatCategory | None = None
    source_id: str | None = None

    @property
    def is_malicious(self) -> bool:
        return self.label == "malicious"

    def to_attack(self) -> Attack:
        """Represent a malicious sample as an ``Attack`` for the runner.

        Benign samples are fed to the runner as raw strings, so this is only
        meaningful for the malicious class.
        """
        return Attack(
            payload=self.text,
            category=self.category or _DEFAULT_MALICIOUS_CATEGORY,
            technique=f"corpus/{self.source}",
            expected_verdict=Verdict.BLOCK,
            difficulty="hard",
        )


@dataclass
class CorpusStats:
    """Provenance summary for a loaded corpus (attached to reports)."""

    total: int = 0
    malicious: int = 0
    benign: int = 0
    by_source: dict[str, int] = field(default_factory=dict)
    skipped_lines: int = 0
    shards: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {
            "total": self.total,
            "malicious": self.malicious,
            "benign": self.benign,
            "by_source": dict(sorted(self.by_source.items())),
            "skipped_lines": self.skipped_lines,
            "shards": sorted(self.shards),
        }


def _parse_line(raw: str, shard: str, lineno: int) -> LabeledSample | None:
    """Parse one JSONL line into a LabeledSample, or None if malformed."""
    raw = raw.strip()
    if not raw:
        return None
    try:
        obj = json.loads(raw)
    except json.JSONDecodeError:
        logger.warning("corpus_bad_json shard=%s line=%d", shard, lineno)
        return None
    if not isinstance(obj, dict):
        logger.warning("corpus_not_object shard=%s line=%d", shard, lineno)
        return None

    text = obj.get("text")
    label = obj.get("label")
    source = obj.get("source") or shard
    if not isinstance(text, str) or not text.strip():
        logger.warning("corpus_missing_text shard=%s line=%d", shard, lineno)
        return None
    if label not in _VALID_LABELS:
        logger.warning(
            "corpus_bad_label shard=%s line=%d label=%r", shard, lineno, label
        )
        return None

    category = None
    if label == "malicious":
        category = _coerce_category(obj.get("category"))

    source_id = obj.get("source_id")
    return LabeledSample(
        text=text,
        label=label,  # type: ignore[arg-type]
        source=str(source),
        category=category,
        source_id=str(source_id) if source_id is not None else None,
    )


class CorpusLoader:
    """Loads labeled evaluation samples from bundled + operator-supplied shards.

    Resolution order:
      1. Bundled ``src/evaluation/data/*.jsonl`` (the reproducible floor).
      2. ``$BULWARK_EVAL_DATASET_DIR/*.jsonl`` (optional, additive) — where an
         operator drops full corpus downloads.

    Both directories are merged; nothing overrides, so pointing at a larger
    external corpus enriches rather than replaces the audited floor.
    """

    def __init__(
        self,
        bundled_dir: Path | None = None,
        external_dir: str | os.PathLike | None = ...,  # type: ignore[assignment]
    ) -> None:
        self._bundled_dir = Path(bundled_dir) if bundled_dir is not None else DEFAULT_DATA_DIR
        # Sentinel default (...) means "read the env var"; an explicit None
        # disables the external dir entirely (useful for hermetic tests).
        self._external_dir: Path | None
        if external_dir is ...:
            env_val = os.environ.get(_EXTERNAL_DIR_ENV)
            self._external_dir = Path(env_val) if env_val else None
        elif external_dir is None:
            self._external_dir = None
        else:
            self._external_dir = Path(external_dir)

    def _shard_paths(self) -> list[Path]:
        paths: list[Path] = []
        for d in (self._bundled_dir, self._external_dir):
            if d and d.is_dir():
                paths.extend(sorted(d.glob("*.jsonl")))
        return paths

    def load(
        self,
        sources: Iterable[str] | None = None,
        labels: Iterable[Label] | None = None,
        limit_per_source: int | None = None,
    ) -> tuple[list[LabeledSample], CorpusStats]:
        """Load samples with optional source/label filters.

        Args:
            sources: if given, keep only samples whose ``source`` is in this set.
            labels: if given, keep only samples with a label in this set.
            limit_per_source: cap the number of samples kept per source (applied
                in file order — deterministic given the vendored shards).

        Returns:
            ``(samples, stats)`` — the loaded samples and a provenance summary.
        """
        source_filter = set(sources) if sources is not None else None
        label_filter = set(labels) if labels is not None else None

        stats = CorpusStats()
        per_source_count: dict[str, int] = {}
        samples: list[LabeledSample] = []

        for path in self._shard_paths():
            shard = path.name
            stats.shards.append(shard)
            try:
                content = path.read_text(encoding="utf-8")
            except OSError as e:
                logger.warning("corpus_shard_unreadable shard=%s err=%s", shard, e)
                continue

            for lineno, raw in enumerate(content.splitlines(), start=1):
                sample = _parse_line(raw, shard, lineno)
                if sample is None:
                    if raw.strip():
                        stats.skipped_lines += 1
                    continue
                if source_filter is not None and sample.source not in source_filter:
                    continue
                if label_filter is not None and sample.label not in label_filter:
                    continue
                if limit_per_source is not None:
                    n = per_source_count.get(sample.source, 0)
                    if n >= limit_per_source:
                        continue
                    per_source_count[sample.source] = n + 1

                samples.append(sample)
                stats.total += 1
                if sample.is_malicious:
                    stats.malicious += 1
                else:
                    stats.benign += 1
                stats.by_source[sample.source] = stats.by_source.get(sample.source, 0) + 1

        return samples, stats


def split_samples(
    samples: Iterable[LabeledSample],
) -> tuple[list[Attack], list[str]]:
    """Split labeled samples into (malicious Attacks, benign texts).

    This is the bridge into ``EvaluationRunner.run_evaluation``, which already
    scores a malicious positive class against a benign negative class and emits
    both confusion matrices. Malicious samples become ``Attack`` objects
    (category-mapped); benign samples become raw prompt strings.
    """
    attacks: list[Attack] = []
    benign: list[str] = []
    for s in samples:
        if s.is_malicious:
            attacks.append(s.to_attack())
        else:
            benign.append(s.text)
    return attacks, benign


def load_corpus(
    sources: Iterable[str] | None = None,
    labels: Iterable[Label] | None = None,
    limit_per_source: int | None = None,
    bundled_dir: Path | None = None,
    external_dir: str | os.PathLike | None = ...,  # type: ignore[assignment]
) -> tuple[list[LabeledSample], CorpusStats]:
    """Convenience wrapper around :class:`CorpusLoader`."""
    loader = CorpusLoader(bundled_dir=bundled_dir, external_dir=external_dir)
    return loader.load(sources=sources, labels=labels, limit_per_source=limit_per_source)
